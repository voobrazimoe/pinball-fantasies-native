// SidebarFont is an independently drawn 8x8 alphabet in the manner of the
// 640-pixel-wide VGA text modes: two-pixel vertical stems, single-pixel
// horizontals, seven rows plus a blank baseline row. The glyphs were authored
// for this native port; no BIOS, ROM, emulator font, or external font was
// used. See docs/runtime-data.md.
var SidebarFont = func() [128 * 8]byte {
	var cells [128 * 8]byte
	for ch, rows := range sidebarGlyphs {
		for row, line := range rows {
			var bits byte
			for col := 0; col < len(line); col++ {
				if line[col] == '#' {
					bits |= 0x80 >> uint(col)
				}
			}
			cells[int(ch)*8+row] = bits
		}
	}
	return cells
}()

